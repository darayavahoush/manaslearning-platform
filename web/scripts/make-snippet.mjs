// Usage: node scripts/make-snippet.mjs [path-to-milo-snippet.html]
// Turns the Milo snippet into lib/milo-snippet.ts so the proxy can inject it.
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'

const src = process.argv[2] || path.join(os.homedir(), 'milo-work', 'milo-snippet.html')
let html = fs.readFileSync(src, 'utf8')
html = html.replace(/https:\/\/vaakbot-api[^'"]*\/api/g, '/api/milo')   // chat goes through our own rewrite
const out = path.join(import.meta.dirname, '..', 'lib', 'milo-snippet.ts')
fs.writeFileSync(out, `// Generated by scripts/make-snippet.mjs. Do not edit.\nexport const MILO_SNIPPET = ${JSON.stringify(html)}\n`)
console.log(`wrote ${out} (${html.length} chars)`)
